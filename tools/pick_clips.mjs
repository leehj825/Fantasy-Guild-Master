// Picks the clips the game uses out of model_check's data/anims.js and writes a compact module (src/clips.js).
// usage: node tools/pick_clips.mjs /path/to/model_check/data/anims.js
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const src = process.argv[2]; if (!src) throw new Error('give the path of anims.js');
const A = (await import(pathToFileURL(src).href)).default;
const PICK = ['idleEase', 'idleCalm', 'walkCalm', 'runCalm', 'slash1', 'slash3', 'attack1', 'attack2', 'attack3', 'attackJump', 'kick', 'slash5', 'brawlPunch', 'brawlSwipe', 'shoot', 'mgBolt', 'mgFire', 'mgNova', 'mgHeal', 'mgBless', 'mgHoly', 'impact', 'die', 'mgBlock', 'blockIdle', 'block', 'kneel'];
const r = v => Math.round(v * 1000) / 1000, out = {};
for (const k of PICK) {
  const c = A[k]; if (!c) throw new Error('missing clip ' + k);
  const t = {}; for (const [b, arr] of Object.entries(c.t)) t[b] = arr.map(v => Array.isArray(v) ? v.map(r) : r(v));
  out[k] = { d: r(c.d), n: c.n, loop: !!c.loop, hit: r(c.hit || 0), t };
}
fs.writeFileSync('src/clips.js', '// Motion clips (Mixamo-derived, from the model_check library). Generated by tools/pick_clips.mjs; do not edit by hand.\nexport default ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'clips,', (fs.statSync('src/clips.js').size / 1024).toFixed(0), 'KB');
